// Offline developer-authored references; this does not evaluate a model.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createWorkspace,addQuestion,addDocument,saveReview,evidenceReport} from '../web/domain.js';
const path=new URL('./paper-attribution.json',import.meta.url);
assert.ok(fs.statSync(path).size<16000);
const f=JSON.parse(fs.readFileSync(path,'utf8'));
for(const p of f.paragraphs)assert.equal(createHash('sha256').update(p.text).digest('hex'),p.sha256);
let s=addDocument(createWorkspace(),f.title,f.paragraphs.map(p=>p.text).join('\n\n'),{type:'paper',author:f.authors,year:f.year,url:f.sourceUrl,locator:'Non-contiguous excerpts: Background quotation + Abstract results; arranged thematically, not original adjacency'});
s=addQuestion(s,f.researchQuestion,'推文计数代表学术交流','仅评价本文牙科论文推文样本中的代表性，不泛化到所有 Twitter 用户。');
const quote='uniquely conversational',start=f.paragraphs[0].text.indexOf(quote);
const annotation={labelId:'topic',quote,start,end:start+quote.length,holder:f.holder,stance:'mentions',stanceQuote:f.paragraphs[0].text,stanceParagraphId:'P007'};
s=saveReview(s,'P007',[annotation],'开发助手参考：仅就引用段落，不能推断本文作者认可。');
assert.equal(evidenceReport(s,'supports').evidence.length,0);
assert.equal(evidenceReport(s,'mentions').evidence.length,1);
s=saveReview(s,'P007',[{...annotation,stance:'opposes',stanceQuote:f.paragraphs[1].text,stanceParagraphId:'P008'}],'开发助手参考：核对非相邻的摘要结果；反对把样本推文计数直接等同于交流，不否定所有对话。');
const report=evidenceReport(s,'opposes');
assert.equal(report.evidence.length,1);
assert.equal(evidenceReport(s,'supports').evidence.length,0);
assert.equal(evidenceReport(s,'mentions').evidence.length,0);
assert.equal(report.evidence[0].holder,f.holder);
assert.equal(report.evidence[0].stanceParagraphId,'P008');
assert.equal(s.reviews.length,2);
const rss=process.resourceUsage().maxRSS/1024;assert.ok(rss<256,'Stop: memory budget exceeded');
const out=new URL('./results/paper-attribution-v1/',import.meta.url);fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(new URL('evidence.json',out),JSON.stringify(report,null,2));
fs.writeFileSync(new URL('report.json',out),JSON.stringify({kind:'offline developer-reference validation',modelCalls:0,source:f.sourceUrl,peakRssMiB:rss,checks:['source hashes','quotation alone excluded from support','author response kept as separate paragraph','holder retained','current summary replaces earlier interpretation without deleting history'],limits:'2 excerpts; fixture <16 KB; process RSS checkpoint <256 MiB; no automatic retry'},null,2));
console.log(JSON.stringify({passed:true,modelCalls:0,peakRssMiB:rss}));
